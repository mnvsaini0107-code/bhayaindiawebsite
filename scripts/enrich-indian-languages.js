for (const [code, trans] of Object.entries(packsData)) {
  const blockRegex = new RegExp(`(${code}:\\s*\\{[\\s\\S]*?translations:\\s*\\{)([\\s\\S]*?)(\\n\\s*\\},)`, "m");
  const match = content.match(blockRegex);
  if (match) {
    let currentBody = match[2];
    let added = "";
    for (const [k, v] of Object.entries(trans)) {
      if (!currentBody.includes(k + ":")) {
        added += `      ${k}: ${JSON.stringify(v)},\n`;
      }
    }
    content = content.replace(blockRegex, match[1] + match[2] + "\n" + added + "    },");
    console.log(`Updated pack: ${code}`);
  } else {
    console.warn(`Could not find pack block for: ${code}`);
  }
}

